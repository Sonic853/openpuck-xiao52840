#!/usr/bin/env python3
"""Build the DX/Seeed Xiao nRF52840 application for factory S140 7.3.0."""

import argparse
import hashlib
import json
import pathlib
import re
import struct
import subprocess
import sys


ROOT = pathlib.Path(__file__).resolve().parents[1]
FQBN = "Seeeduino:nrf52:xiaonRF52840"
CORE_VERSION = "1.1.13"
TINYUSB_VERSION = "3.6.0"


def run(*args):
    return subprocess.check_output(args, cwd=ROOT, text=True).strip()


def validate_uf2(path):
    data = path.read_bytes()
    if not data or len(data) % 512:
        raise ValueError("Invalid UF2 length")
    image = {}
    seen = set()
    count = len(data) // 512
    for offset in range(0, len(data), 512):
        block = data[offset:offset + 512]
        m0, m1, flags, addr, size, index, total, family = struct.unpack_from(
            "<8I", block
        )
        if ((m0, m1) != (0x0A324655, 0x9E5D5157)
                or struct.unpack_from("<I", block, 508)[0] != 0x0AB16F30
                or flags != 0x2000 or family != 0xADA52840
                or size != 256 or total != count or index >= count
                or index in seen):
            raise ValueError("Invalid UF2 block")
        if addr < 0x27000 or addr + size > 0x86000 or addr % 256:
            raise ValueError(f"UF2 block outside Xiao application: {addr:#x}")
        seen.add(index)
        for i, byte in enumerate(block[32:32 + size]):
            if addr + i in image:
                raise ValueError("Overlapping UF2 blocks")
            image[addr + i] = byte
    start, end = min(image), max(image) + 1
    if start != 0x27000 or len(image) != end - start:
        raise ValueError("Missing Xiao vector table or sparse application")
    sp, reset = struct.unpack("<II", bytes(image[start + i] for i in range(8)))
    if not (0x20006000 <= sp <= 0x20040000 and sp % 8 == 0
            and reset & 1 and start <= (reset & ~1) < end):
        raise ValueError("Invalid Xiao application vectors")
    print(f"Verified UF2: {start:#x}..{end:#x}, SP={sp:#x}, reset={reset:#x}")
    print(f"SHA256: {hashlib.sha256(data).hexdigest()}")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--cli", default="arduino-cli")
    parser.add_argument("--tinyusb", type=pathlib.Path)
    parser.add_argument("--verify", type=pathlib.Path,
                        help="Only validate an already built UF2")
    args = parser.parse_args()
    if args.verify:
        validate_uf2(args.verify)
        return

    data = pathlib.Path(run(args.cli, "config", "get", "directories.data"))
    user = pathlib.Path(run(args.cli, "config", "get", "directories.user"))
    core = data / "packages/Seeeduino/hardware/nrf52" / CORE_VERSION
    tinyusb = args.tinyusb or user / "libraries/Adafruit_TinyUSB_Library"
    if not (core / "platform.txt").is_file():
        raise SystemExit(f"Install Seeeduino:nrf52@{CORE_VERSION} first")
    board = json.loads(run(args.cli, "board", "details", "-b", FQBN,
                           "--format", "json"))
    properties = dict(item.split("=", 1) for item in board["build_properties"])
    if (board["version"] != CORE_VERSION
            or properties["build.sd_version"] != "7.3.0"
            or properties["build.ldscript"] != "nrf52840_s140_v7.ld"):
        raise SystemExit("Unexpected Xiao core version or SoftDevice layout")
    props = (tinyusb / "library.properties").read_text()
    if not re.search(rf"^version={re.escape(TINYUSB_VERSION)}$", props, re.M):
        raise SystemExit(f"Install Adafruit TinyUSB Library@{TINYUSB_VERSION}")

    output = ROOT / "build/xiao"
    output.mkdir(parents=True, exist_ok=True)
    git_hash = run("git", "rev-parse", "--short=8", "HEAD")
    dirty = int(bool(run("git", "status", "--porcelain")))
    (ROOT / "OpenPuck/git_version.h").write_text(
        '// Generated by tools/build-xiao.py; do not commit.\n#pragma once\n'
        '#define OPK_BUILD_VERSION ""\n'
        f'#define OPK_GIT_HASH "{git_hash}"\n#define OPK_GIT_DIRTY {dirty}\n'
    )
    flags = (
        "-DNRF52840_XXAA {build.flags.usb} -DCFG_TUD_HID=6 "
        "-DCFG_TUD_TASK_QUEUE_SZ=512 -DCFG_TUD_VENDOR_TX_BUFSIZE=256 "
        "-DOPK_RF_JOURNAL_BASE=0x86000"
    )
    link = (
        "-Wl,--wrap=tud_vendor_control_xfer_cb "
        "-Wl,--wrap=tud_descriptor_string_cb "
        "-Wl,--wrap=usbd_control_xfer_cb "
        "-Wl,--section-start=.rf_journal_guard=0x86000"
    )
    # Seeed bundles TinyUSB 1.7.0; its config include precedes library paths.
    includes = f'-I"{(tinyusb / "src/arduino").as_posix()}"'
    command = [
        args.cli, "compile", "--clean", "-b", FQBN,
        "--build-path", str(ROOT / "build/cache/xiao"),
        "--output-dir", str(output), "--library", str(tinyusb),
        "--build-property", f"build.extra_flags={flags}",
        "--build-property", f"compiler.c.elf.extra_flags={link}",
        "--build-property", f"compiler.c.extra_flags={includes}",
        "--build-property", f"compiler.cpp.extra_flags={includes}",
        "OpenPuck",
    ]
    subprocess.run(command, cwd=ROOT, check=True)
    uf2 = output / "OpenPuck-xiao-s140-7.3.0.uf2"
    subprocess.run([
        sys.executable, str(core / "tools/uf2conv/uf2conv.py"),
        "-f", "0xADA52840", "-c", "-o", str(uf2),
        str(output / "OpenPuck.ino.hex"),
    ], check=True)
    validate_uf2(uf2)
    print(uf2)


if __name__ == "__main__":
    main()
